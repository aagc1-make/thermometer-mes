export function navigationIcon(path, title, isGroup = false) {
  if (/^(?:https?:|mailto:|tel:|\/\/)/i.test(path || '')) return 'nav-external-link'
  if (isGroup) return 'nav-' + (Object.prototype.hasOwnProperty.call(groupIcons, title) ? groupIcons[title] : 'folder')
  const normalized = String(path || '').replace(/\/+$/, '')
  return 'nav-' + (pageIcons[normalized] || 'file-description')
}
